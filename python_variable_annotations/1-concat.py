#!/usr/bin/env python3
"""
This module provides a function for basic string concatenation with
type annotations.
"""


def concat(str1: str, str2: str) -> str:
    """
    Concatenates two strings together and returns the result.

    Parameters:
    str1 (str): The first string.
    str2 (str): The second string.

    Returns:
    str: The concatenated string containing str1 followed by str2.
    """
    return str1 + str2
