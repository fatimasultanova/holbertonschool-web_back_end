#!/usr/bin/env python3
"""
This module provides a function to safely convert floating-point numbers
into their string representations with type annotations.
"""


def to_str(n: float) -> str:
    """
    Takes a float n as an argument and returns its string representation.

    Parameters:
    n (float): The floating-point number to convert.

    Returns:
    str: The string representation of the float n.
    """
    return str(n)
